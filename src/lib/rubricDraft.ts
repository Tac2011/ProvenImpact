import type { ExampleRating } from './rubric';

// Reads Rubric_v2_Draft.md (Todd and Maggi's markup copy) into rubric rows. Sections are
// "## N. Label"; review-only marks and notes are dropped so the AI never sees them.

export interface DraftExample {
  story: string;
  rating: ExampleRating;
  why: string;
}

export interface DraftCompetency {
  key: string;
  label: string;
  definition: string;
  strong: string;
  moderate: string;
  notEvidence: string;
  examples: DraftExample[];
}

const RATINGS: Record<string, ExampleRating> = { Strong: 'strong', Moderate: 'moderate', 'Not evidence': 'not_evidence' };

const clean = (text: string) =>
  text.replace(/\*\*\[(?:CHANGED|NEW)\]\*\*/g, '').replace(/\s+/g, ' ').trim();

export function parseRubricDraft(markdown: string): DraftCompetency[] {
  return markdown
    .split(/^## (?=\d+\.\s)/m)
    .slice(1)
    .map((section) => {
      const lines = section.split(/\r?\n/);
      const label = lines[0].replace(/^\d+\.\s*/, '').replace(/\[NEW\]/, '').trim();
      const field = (name: string) => {
        const prefix = `**${name}:**`;
        const line = lines.find((l) => l.startsWith(prefix));
        if (!line) throw new Error(`${label}: missing "${name}"`);
        return clean(line.slice(prefix.length));
      };
      const examples: DraftExample[] = [];
      lines.forEach((line, i) => {
        const m = line.match(/^- \*\*(?:\[NEW\] )?(Strong|Moderate|Not evidence):\*\*\s*(.+)$/);
        if (!m) return;
        const next = lines[i + 1]?.trim() ?? '';
        examples.push({ story: clean(m[2]), rating: RATINGS[m[1]], why: next.startsWith('*Why:*') ? clean(next.slice(6)) : '' });
      });
      if (examples.length === 0) throw new Error(`${label}: no examples`);
      return {
        key: label.toLowerCase(),
        label,
        definition: field('Definition'),
        strong: field('Strong'),
        moderate: field('Moderate'),
        notEvidence: field("Doesn't count"),
        examples,
      };
    });
}

const q = (text: string) => `$q$${text}$q$`;

export function rubricSql(version: number, notes: string, competencies: DraftCompetency[]): string {
  const draft = `from rubric_versions where version = ${version} and published_at is null;`;
  const rows = competencies.map((c) => {
    const json = JSON.stringify(c.examples);
    const texts = [c.label, c.definition, c.strong, c.moderate, c.notEvidence, json];
    if (texts.some((t) => t.includes('$q$') || t.includes('$j$'))) throw new Error(`${c.label}: text contains $q$ or $j$`);
    return [
      'insert into rubric_competencies',
      '  (rubric_version_id, key, label, definition, strong_evidence, moderate_evidence, not_evidence, examples)',
      `select id, '${c.key}', ${q(c.label)}, ${q(c.definition)}, ${q(c.strong)}, ${q(c.moderate)}, ${q(c.notEvidence)}, $j$${json}$j$::jsonb`,
      draft,
    ].join('\n');
  });
  return [
    `-- Rubric version ${version}, generated by scripts/build-rubric-sql.ts from the approved draft.`,
    '-- Run in the Supabase SQL editor. Safe to rerun while the version is a draft: it replaces',
    '-- the competencies. Once published, nothing here changes anything.',
    '',
    `insert into rubric_versions (version, notes) values (${version}, ${q(notes)}) on conflict (version) do nothing;`,
    '',
    `delete from rubric_competencies where rubric_version_id in (select id ${draft.replace(';', ')')};`,
    '',
    rows.join('\n\n'),
    '',
    `-- Check: expect ${competencies.length} rows.`,
    `select key, label from rubric_competencies where rubric_version_id = (select id from rubric_versions where version = ${version});`,
    '',
  ].join('\n');
}
